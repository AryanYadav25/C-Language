#include <stdio.h>

int main() {
    char ch = 'a';
    ch = '\n'; // Represents new line 
    printf("Hey my name is \n Aryan\n"); // put aryan in next line
    printf("Hey my name is \t Aryan\n"); // put a gap between is and aryan
    printf("Hey my name is \" Aryan\n"); // add a double quote after is 
    printf("Hey my name is \\ Aryan\n"); // add a \ after is 

    return 0;
}